import type { Database } from "bun:sqlite";
import type { Config } from "../config";
import { getEmail, insertEvaluation, insertRun, type Email } from "../db/queries";
import { sanitizeError } from "../providers/http";
import {
  ProviderError,
  type DecisionProvider,
  type ProviderOutput,
  type ReplyGenerator,
} from "../providers/types";
import type {
  ComparisonResponse,
  Decision,
  EmailDetectionDecision,
  ModelRoutingDecision,
  Provider,
  ProviderResult,
  ResponseQualityDecision,
} from "../schemas";
import type { EmailInput, UseCase } from "../usecases/definitions";

export const LATENCY_METHOD =
  "Wall-clock time measured on the backend around each provider HTTP request (includes network round trip). Jev and OpenAI run concurrently.";

export type Deps = {
  db: Database;
  config: Config;
  jev: DecisionProvider;
  openai: DecisionProvider & ReplyGenerator;
};

export class AppError extends Error {
  constructor(
    readonly status: number,
    readonly code: string,
    message: string,
  ) {
    super(message);
  }
}

type Attempt = { ok: true; output: ProviderOutput<Decision>; latencyMs: number } | {
  ok: false;
  error: ProviderError;
  latencyMs: number | null;
};

export async function attempt(provider: Provider, fn: () => Promise<ProviderOutput<Decision>>): Promise<Attempt> {
  const start = performance.now();
  try {
    const output = await fn();
    return { ok: true, output, latencyMs: Math.round(performance.now() - start) };
  } catch (err) {
    const latencyMs = Math.round(performance.now() - start);
    if (err instanceof ProviderError) {
      // A config error means no request was made, so there is no latency to report.
      return { ok: false, error: err, latencyMs: err.kind === "config" ? null : latencyMs };
    }
    const message = err instanceof Error ? err.message : String(err);
    console.error(`[${provider}] unexpected error:`, sanitizeError(message));
    return {
      ok: false,
      error: new ProviderError("invalid_output", `Unexpected error while processing the ${provider} response`),
      latencyMs,
    };
  }
}

/** The single value that is compared for agreement and accuracy. */
export function decisionKey(useCase: UseCase, decision: Decision): string {
  switch (useCase) {
    case "email_detection":
      return (decision as EmailDetectionDecision).label;
    case "model_routing":
      return (decision as ModelRoutingDecision).tierId;
    case "response_quality":
      return (decision as ResponseQualityDecision).outcome;
  }
}

export function computeAgreement(useCase: UseCase, jev: ProviderResult, openai: ProviderResult): boolean | null {
  if (jev.status !== "completed" || openai.status !== "completed" || !jev.decision || !openai.decision) return null;
  return decisionKey(useCase, jev.decision) === decisionKey(useCase, openai.decision);
}

/** Accuracy needs ground truth: only Email Detector emails with an expected label qualify. */
export function computeCorrectness(useCase: UseCase, expectedLabel: string | null, result: ProviderResult): boolean | null {
  if (useCase !== "email_detection" || !expectedLabel) return null;
  if (result.status !== "completed" || !result.decision) return null;
  return decisionKey(useCase, result.decision) === expectedLabel;
}

function toResult(runId: string, provider: Provider, a: Attempt): ProviderResult {
  if (a.ok) {
    return {
      runId,
      provider,
      status: "completed",
      decision: a.output.decision,
      probabilities: a.output.probabilities,
      confidence: a.output.confidence,
      latencyMs: a.latencyMs,
      model: a.output.model,
      usage: a.output.usage,
      error: null,
      errorKind: null,
    };
  }
  return {
    runId,
    provider,
    status: "failed",
    decision: null,
    probabilities: null,
    confidence: null,
    latencyMs: a.latencyMs,
    model: null,
    usage: null,
    error: a.error.message,
    errorKind: a.error.kind,
  };
}

async function resolveCandidateReply(
  deps: Deps,
  email: Email,
  override: string | undefined,
): Promise<{ text: string; source: string }> {
  if (override) return { text: override, source: "request" };
  if (email.candidateReply) return { text: email.candidateReply, source: "stored" };

  const model = deps.config.openai.tierModels.balanced;
  if (!model) {
    throw new AppError(
      400,
      "candidate_reply_missing",
      "This email has no candidate reply. Provide candidateReply, or set OPENAI_BALANCED_MODEL so one can be generated.",
    );
  }
  try {
    const draft = await deps.openai.generateReply(toInput(email), model);
    return { text: draft.text, source: `generated by ${draft.model}` };
  } catch (err) {
    const message = err instanceof Error ? err.message : String(err);
    throw new AppError(502, "candidate_generation_failed", `Could not generate a candidate reply: ${message}`);
  }
}

function toInput(email: Email): EmailInput {
  return { from: email.from, subject: email.subject, body: email.body };
}

export async function compare(
  deps: Deps,
  emailId: string,
  useCase: UseCase,
  opts: { candidateReply?: string; benchmarkId?: string } = {},
): Promise<ComparisonResponse> {
  const email = getEmail(deps.db, emailId);
  if (!email) throw new AppError(404, "not_found", `Email ${emailId} not found`);

  const input = toInput(email);
  const snapshot: Record<string, unknown> = { useCase, email: input };

  let jevCall: () => Promise<ProviderOutput<Decision>>;
  let openaiCall: () => Promise<ProviderOutput<Decision>>;

  switch (useCase) {
    case "email_detection":
      jevCall = () => deps.jev.classifyEmail(input);
      openaiCall = () => deps.openai.classifyEmail(input);
      break;
    case "model_routing": {
      const resolve = async (p: DecisionProvider) => {
        const out = await p.routeEmail(input);
        const model = deps.config.openai.tierModels[out.decision.tierId];
        return { ...out, decision: { ...out.decision, model } };
      };
      jevCall = () => resolve(deps.jev);
      openaiCall = () => resolve(deps.openai);
      break;
    }
    case "response_quality": {
      const candidate = await resolveCandidateReply(deps, email, opts.candidateReply);
      snapshot.candidateReply = candidate.text;
      snapshot.candidateSource = candidate.source;
      jevCall = () => deps.jev.evaluateReply(input, candidate.text);
      openaiCall = () => deps.openai.evaluateReply(input, candidate.text);
      break;
    }
  }

  // Independent, concurrent calls: neither provider sees the other's answer.
  const [jevAttempt, openaiAttempt] = await Promise.all([attempt("jev", jevCall), attempt("openai", openaiCall)]);

  const jev = toResult(crypto.randomUUID(), "jev", jevAttempt);
  const openai = toResult(crypto.randomUUID(), "openai", openaiAttempt);
  const agreement = computeAgreement(useCase, jev, openai);
  const jevCorrect = computeCorrectness(useCase, email.expectedLabel, jev);
  const openaiCorrect = computeCorrectness(useCase, email.expectedLabel, openai);
  const evaluationId = crypto.randomUUID();

  deps.db.transaction(() => {
    for (const [result, a] of [
      [jev, jevAttempt],
      [openai, openaiAttempt],
    ] as const) {
      insertRun(deps.db, {
        id: result.runId,
        emailId,
        useCase,
        provider: result.provider,
        status: result.status,
        inputSnapshot: snapshot,
        output: a.ok
          ? {
              decision: result.decision,
              probabilities: result.probabilities,
              confidence: result.confidence,
              model: result.model,
              usage: result.usage,
              raw: a.output.raw,
            }
          : null,
        latencyMs: result.latencyMs,
        errorKind: result.errorKind,
        errorMessage: result.error,
      });
    }
    insertEvaluation(deps.db, {
      id: evaluationId,
      emailId,
      useCase,
      jevRunId: jev.runId,
      openaiRunId: openai.runId,
      agreement,
      expectedLabel: useCase === "email_detection" ? email.expectedLabel : null,
      jevCorrect,
      openaiCorrect,
      benchmarkId: opts.benchmarkId ?? null,
    });
  })();

  return {
    emailId,
    useCase,
    evaluationId,
    input: snapshot,
    results: { jev, openai },
    comparison: {
      agreement,
      groundTruthCorrectness:
        useCase === "email_detection" && email.expectedLabel
          ? { expected: email.expectedLabel, jev: jevCorrect, openai: openaiCorrect }
          : null,
      latencyMethod: LATENCY_METHOD,
    },
  };
}
